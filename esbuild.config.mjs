import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const pdfWorkerPlugin = {
	name: 'pdf-worker-text',
	setup(build) {
		build.onResolve(
			{ filter: /^pdfjs-dist\/build\/pdf\.worker\.min\.mjs$/ },
			() => ({
				path: resolve('node_modules/pdfjs-dist/build/pdf.worker.min.mjs'),
				namespace: 'pdf-worker-text',
			})
		);
		build.onLoad(
			{ filter: /.*/, namespace: 'pdf-worker-text' },
			async (args) => ({
				contents: await readFile(args.path, 'utf8'),
				loader: 'text',
			})
		);
	},
};

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
	plugins: [pdfWorkerPlugin],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
